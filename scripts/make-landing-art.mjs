// Generates packages/web/src/landing/art.generated.ts: three real drawings of the app (plates of the owner's example project, cut with
// the app's own engine and drawn with the app's own renderer) for the landing page, in Polish and English. They are inlined as SVG so the
// theme colours (CSS variables) apply, and so the landing page needs no engine run for them.
//   node scripts/make-landing-art.mjs
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';

const out = 'packages/web/src/landing/art.generated.ts';
const tmp = 'node_modules/.cache/make-landing-art.mjs';
mkdirSync('node_modules/.cache', { recursive: true });
await build({
  stdin: { contents: `
import { exampleProject } from './packages/web/src/state/project';
import { buildRequest } from './packages/web/src/cut/request';
import { computeCut } from '@slabs/core';
import { LABELS, cutSheets, plateMarks } from '@slabs/render';
import { roomPrefix, setLang, setNames } from './packages/web/src/i18n';
const r1 = (v) => Math.round(v * 10) / 10;
const p = exampleProject('Przykład');
const R = computeCut({ ...buildRequest(p), maxIters: 400, timeMs: Infinity });
const art = {};
for (const lang of ['pl', 'en']) {
  setLang(lang); setNames(p.names, p.roomOrder);
  const prefix = roomPrefix;
  const nf = (v) => new Intl.NumberFormat(lang, { maximumFractionDigits: 1 }).format(v);
  const sheets = cutSheets(R, p.settings.minOffcutCm, lang === 'pl' ? 'op.' : 'band', p.settings.minStripCm, prefix);
  const draw = (sh) => plateMarks(sh, R.PL, R.PW, { scale: 1, labels: LABELS[lang], nf, prefix, tongue: R.tongue?.t, keep: lang === 'pl' ? 'zostaje' : 'keep' });
  const rooms = (sh) => new Set(sh.items.filter((i) => !i.band).map((i) => i.room));
  const real = sheets.filter((s) => !s.extra);
  // 1. a plate whose pieces come from several rooms
  const together = real.filter((s) => rooms(s).size >= 3 && s.items.length >= 4 && s.items.length <= 9).sort((a, b) => b.use - a.use)[0] ?? real.filter((s) => rooms(s).size >= 2)[0];
  // 2. a plate with tongue and groove letters on many pieces, little else
  const grooves = real.filter((s) => s !== together && s.items.filter((i) => i.edges.length >= 2).length >= 3 && s.items.length <= 6).sort((a, b) => b.items.length - a.items.length)[0] ?? real.find((s) => s !== together);
  // 3. a plate with slanted cuts (the saw sheet matters most there)
  const slanted = real.filter((s) => s !== together && s !== grooves && s.items.some((i) => i.slants.length) && s.items.length >= 2 && s.items.length <= 7).sort((a, b) => b.use - a.use)[0] ?? real.find((s) => s !== together && s !== grooves);
  const pack = (sh) => { const d = draw(sh); return { no: sh.no, of: sheets.length, svg: d.svg, w: d.w, h: d.h, use: Math.round(sh.use * 100),
    rows: sh.items.filter((i) => !i.band).map((i) => ({ label: i.label, l: r1(i.l), w: r1(i.w), sliver: i.sliver, slanted: i.slants.length > 0 })) }; };
  art[lang] = { together: pack(together), grooves: pack(grooves), sheet: pack(slanted), plates: R.plates.length, PL: R.PL, PW: R.PW };
}
globalThis.__art = art;
`, resolveDir: process.cwd(), loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', outfile: tmp, logLevel: 'error',
  alias: { '@slabs/core': './packages/core/src/index.ts', '@slabs/render': './packages/render/src/index.ts' },
});
await import(new URL('../' + tmp, import.meta.url).href);
const art = globalThis.__art;
const size = JSON.stringify(art).length;
writeFileSync(out, `// Generated by scripts/make-landing-art.mjs from the example project (real plates, real renderer). Do not edit.\nexport interface ArtPlate { no: number; of: number; svg: string; w: number; h: number; use: number; rows: Array<{ label: string; l: number; w: number; sliver: boolean; slanted: boolean }> }\nexport interface ArtSet { together: ArtPlate; grooves: ArtPlate; sheet: ArtPlate; plates: number; PL: number; PW: number }\nexport const ART: Record<'pl' | 'en', ArtSet> = ${JSON.stringify(art)};\n`);
console.log('written', out, (size / 1024).toFixed(0) + ' kB');
